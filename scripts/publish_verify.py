def reject_retargeting(extra: list[str]) -> None:
    """Refuse every forwarded flag that would point the run away from the loopback."""
    for argument in extra:
        flag = argument.split("=", 1)[0]
        if flag in RETARGETING_FLAGS:
            fail(f"{flag} would retarget the run and cannot be forwarded")


def split_exclusions(extra: list[str]) -> tuple[list[str], list[str]]:
    """Split the caller's forwarded flags into exclusions and the rest.

    `--exclude <name>` and `--exclude=<name>` are cargo's own workspace
    publish spellings, and release.yml's pre-publish step forwards exactly the
    flags its upload rounds carry. The run consumes them -- everything else
    (`--no-verify`) is the run's own mode switch -- and an excluded name keeps
    only its resolution-set membership (see the module docstring). The
    returned names are validated against the workspace before any cargo work;
    a value with no name fails here.

    Returns:
        The excluded member names, and the flags that keep forwarding.

    """
    excluded: list[str] = []
    rest: list[str] = []
    index = 0
    while index < len(extra):
        argument = extra[index]
        if argument == "--exclude":
            if index + 1 >= len(extra):
                fail("--exclude needs a member name")
            excluded.append(extra[index + 1])
            index += 2
        elif argument.startswith("--exclude="):
            excluded.append(argument.split("=", 1)[1])
            index += 1
        else:
            rest.append(argument)
            index += 1
    return excluded, rest


def fail(message: str) -> NoReturn:
    """Report the run's failure on stderr and exit nonzero.

    Raises:
        SystemExit: Always, with exit code 1.

    """
    print(f"publish-verify: {message}", file=sys.stderr)
    raise SystemExit(1)


def clear_cargo_staging(rust: Path) -> None:
    """Remove Cargo's temporary publish-staging directories, nothing else.

    Residue from a previous round (`CARGO_STAGING_DIRS` under
    `rust/target/package`) poisons the next round, so every publish round
    starts them clean. Runs under the same-workspace lock; packaged
    artifacts and everything else under `target/package` are never touched.
    A staging directory that cannot be removed fails the run loud -- failing
    beats certifying against residue the run could not clear.

    """
    for name in CARGO_STAGING_DIRS:
        directory = rust / "target" / "package" / name
        if not directory.exists():
            continue
        try:
            shutil.rmtree(directory)
        except OSError as exc:
            fail(f"cannot clear cargo staging directory {directory}: {exc}")


def receipt_problems(covered: set[str], receipt_names: set[str]) -> str | None:
    """Compare the upload receipts against the eligible covered set.

    The receipts are what actually uploaded; the covered set is what the run
    certifies. They must be the same names: a missing receipt means an
    eligible member never uploaded (the run would certify a member the
    registry never accepted), an unexpected receipt means something outside
    the certified set uploaded (the run would stay silent about an upload it
    never accounted for).

    Returns:
        None on an exact match, otherwise one message naming both the
        missing and the unexpected names.

    """
    missing = sorted(covered - receipt_names)
    unexpected = sorted(receipt_names - covered)
    if not missing and not unexpected:
        return None
    parts = []
    if missing:
        parts.append("no upload receipt for: " + ", ".join(missing))
    if unexpected:
        parts.append("unexpected upload receipt for: " + ", ".join(unexpected))
    return "; ".join(parts)


