#!/usr/bin/env python3
"""The publish-verify loopback registry: a non-uploading `cargo publish --dry-run` that resolves.

# live-invariant gate (ADR-087 D2): drives the publish-blocked census and the
# live workspace manifests; not tripwire precedent.

The problem
-----------

`cargo publish` rewrites every path dependency at packaging: the source key is
stripped and what remains is a version requirement that must resolve on
crates.io. Under ADR-009 lockstep versioning, a fresh release bumps every
member to a version crates.io has never seen, so the plain dry run dies on the
first member that a later member requires -- and `--no-verify` changes
nothing, because dependency resolution happens before any verify build. The
real `cargo publish --workspace` survives the same shape only because it
uploads members in dependency order, so each sibling is index-visible by the
time its dependents are packaged; a non-uploading verification cannot use that
ordering.

The mechanism
-------------

For the duration of one run this script stands up ONE Cargo-owned loopback
registry and lets cargo drive it exactly like crates.io. The registry lives in
a fresh per-run directory under `rust/target/`, is served over loopback on an
ephemeral port (cargo rejects `file://` sparse indexes), and implements the
three protocol surfaces cargo's publish flow needs: the sparse index (entries
cargo itself generates at upload), the `.crate` download tree, and the Publish
API upload endpoint. Two cargo seams cooperate, because neither can do the
whole job alone:

1. RESOLUTION. `source.crates-io.replace-with` points plain version-req
   resolution -- the rewritten manifests' shape -- at the loopback index. The
   source-replacement seam cannot carry uploads (cargo hardcodes its upload
   API to https://crates.io for it), so it resolves only.
2. PUBLISH. `cargo publish --registry <name>` with a `[registries.<name>]`
   table (index + dummy token) inside the run-owned `CARGO_HOME` uploads for
   real -- to the loopback, the only endpoint that table names. Cargo packages
   each member, uploads the framed Publish API payload, and polls the index
   until the entry it generated is visible, so `cargo publish --workspace`
   orders the members and stages the siblings itself; this script writes no
   Cargo metadata and orders nothing.

A run therefore proceeds in two cargo-owned rounds over the same registry:

1. The population round (`cargo publish --workspace --registry <name>
   --no-verify`) uploads every covered member without building. Each upload's
   index entry is generated by cargo from the packaged manifest and mapped
   mechanically onto the sparse-index spelling by the registry server
   (`version_req` becomes `req`, a dependency renamed through `package = ...`
   keeps the index rename convention, `dep:`-bearing features split into
   `features2` behind the `v: 2` marker, and the checksum is the sha256 of the
   uploaded `.crate`). This is the RESOLUTION set: after it, every covered
   member resolves like a live crates.io crate.
2. The verification round (`cargo publish --workspace --registry <name>
   --dry-run`, omitted in the `--no-verify` form) verify-builds the
   VERIFICATION set -- the covered members the caller did not `--exclude` --
   against the populated registry, then aborts each upload (nothing ever
   leaves the loopback).

The lock's crates.io-sourced external crates are mirrored verbatim from the
real crates.io sparse index into the same registry, so the loopback can never
satisfy a requirement the real registry cannot; a mirror fetch that comes up
empty fails the run loudly instead of certifying a partial oracle. A pin
locked to a path, a git repository, or an alternate registry fails the run
loudly too: resolving it by name would serve a same-named stranger.

Members the census withholds (genuinely unresolvable external/git shapes) are
excluded from both rounds by name and keep their file-inclusion coverage
through `cargo package --list`, exactly as before. `publish = false` members
are cargo-skipped and therefore not eligible for the covered set at all. The
coverage check fails closed: covered lines print only after the population
round has succeeded, and the upload receipts must name exactly the eligible
covered set -- a missing receipt (certifying a member the registry never
accepted) and an unexpected receipt (an upload the run never accounted for)
both fail the run. A member whose `publish`
allowlist names specific registries fails loud: cargo refuses to carry such a
member to any other registry name, and the one registry this run can drive is
the loopback. Caller flags that would retarget the run (`--registry`,
`--index`, `--token`, `--config`) are refused.

The two member sets stay distinct. The RESOLUTION set is every publishable
non-withheld member: each is uploaded to the loopback (Cargo-generated entry,
exact uploaded checksum), so any member's rewritten manifest resolves against
every sibling at the lockstep version -- which is what crates.io actually
holds when a sibling is live. The VERIFICATION set is the members that get
their own verify build. The release pre-publish step forwards cargo's own
`--exclude <name>` flags for members the live-set audit
(`crates_io_pending.sh --classify`) reports already live at this version; an
exclusion moves a member out of the verification round only -- it stays in the
resolution set, because an already-live member cannot be re-uploaded and
re-verifying it is precisely what makes a resumed re-run expensive. A fresh
tag forwards nothing, so every pending member verifies, and the release step
exits before any packaging when the audit reports nothing pending. The flags
cannot be forwarded to the rounds themselves: a `--workspace` round consumes
them on the caller's behalf, and the script validates every excluded name
against the workspace before any cargo work -- an `--exclude` naming a
non-member fails loud, mirroring cargo's own package-selection error; census
withholding is independent of and unchanged by exclusions.

Every cargo invocation of a run executes with `CARGO_HOME` pointed at the
run's own directory inside its per-run directory: the named-registry token and
source table live there, the loopback-registry caches and staging state cargo
writes during the rounds (`127.0.0.1-*` residue) land there and are removed
with the run directory, and the caller's real Cargo home -- and any real
token inside it -- stays byte-for-byte unread and unchanged, and every token
environment override (`CARGO_TOKEN`, the `CARGO_REGISTRY_*` legacy spellings,
and every named-registry `CARGO_REGISTRIES_*_TOKEN`) is stripped from the
cargo child environment, so cargo's env-over-config preference can never put
a real credential ahead of the run's own. The only
credential the run holds is a fixed dummy token, recorded per upload by the
registry server itself, so every upload receipt proves both the loopback
endpoint and the dummy auth. Runs sharing one workspace serialize their cargo
phases through an interprocess lock (`rust/target/publish-verify.lock`, an
`flock` held from the first cargo resolution to the last publish round):
`rust/target/package` staging and the lockfile cannot interleave between two
same-tree runs, while the lock path is derived from the tree root, so runs in
different workspaces never wait on each other. Under that lock, each publish
round first removes Cargo's own temporary staging directories from a previous
round (`rust/target/package/tmp-crate` and `tmp-registry` -- residue a killed
run leaves behind poisons a rerun) and touches nothing else under
`target/package`, packaged artifacts above all. A second same-tree run waits a
bounded time (`PUBLISH_VERIFY_LOCK_WAIT_SECONDS`, default 1800 seconds) and
then fails loud with an error naming the lock file and the recorded holder;
the lock file itself is never deleted, because removing an `flock`'d file
would let a waiter acquire against an inode the holder no longer holds.
Mirror fetches carry an explicit timeout, bounded retries with backoff, and a
failure naming the crate and URL; in the `--no-verify` form only index
metadata is mirrored, because cargo resolves a no-verify run from the index
alone.

Exit codes: 0 covered, 1 census findings / upload-round / resolution failure,
2 census refused to certify.
"""

