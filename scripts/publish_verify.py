def index_rel(name: str) -> str:
    """Compute the crates.io sparse-index path for a crate name.

    Returns:
        The path under the index root, following crates.io's documented
        bucketing (see the `INDEX_LEN_*` constants).

    """
    if len(name) == INDEX_LEN_ONE:
        return f"3/{name}"
    if len(name) == INDEX_LEN_TWO:
        return f"2/{name}"
    if len(name) == INDEX_LEN_THREE:
        return f"3/{name[0]}/{name}"
    return f"{name[:2]}/{name[2:4]}/{name}"


def _source_problem(name: str, version: str, source: str | None) -> str:
    if source is None:
        return (
            f"{name} {version} is locked to a path source, not crates.io -- "
            "the loopback mirrors crates.io pins only"
        )
    return (
        f"{name} {version} is locked to {source}, not crates.io -- "
        "the loopback mirrors crates.io pins only"
    )


def lock_externals(
    lock_path: Path, member_names: set[str]
) -> tuple[dict[str, set[str]], list[str]]:
    """Collect the crates.io packages the lockfile pins, keyed by crate name.

    The loopback mirrors what crates.io serves, so only a pin whose locked
    source is crates.io is ever mirrored. A non-member locked to a path, a git
    repository, or an alternate registry must fail the run loudly instead:
    mirroring it would resolve the pin by name against crates.io and serve
    whatever same-named stranger the registry hosts.

    Returns:
        The externals -- versions to mirror keyed by crate name -- and the
        problems: one message per pin whose source the loopback cannot serve.

    """
    doc = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    externals: dict[str, set[str]] = {}
    problems: list[str] = []
    for package in doc.get("package", []):
        name = package["name"]
        if name in member_names:
            continue
        source = package.get("source")
        if source in CRATES_IO_SOURCES:
            externals.setdefault(name, set()).add(package["version"])
        else:
            problems.append(_source_problem(name, package["version"], source))
    return externals, problems


def fetch_bytes(
    url: str,
    *,
    timeout: float = FETCH_TIMEOUT_SECONDS,
    attempts: int = FETCH_ATTEMPTS,
    backoff: float = FETCH_BACKOFF_SECONDS,
) -> bytes:
    """Fetch a URL with an explicit timeout and bounded retries with backoff.

    Only transient failures retry -- connection, DNS, timeout, and 5xx
    statuses; a 4xx is a definitive answer about what the endpoint serves
    and fails immediately. Exhausted retries raise with the URL and the
    attempt count, so the caller's failure names what to check.

    Returns:
        The response body.

    Raises:
        urllib.error.HTTPError: A 4xx answer, raised unretouched.
        RuntimeError: The endpoint stayed unreachable for `attempts` tries.

    """
    last_error: Exception | None = None
    for attempt in range(1, attempts + 1):
        try:
            with urllib.request.urlopen(url, timeout=timeout) as response:
                body: bytes = response.read()
                return body
        except urllib.error.HTTPError as exc:
            exc.close()
            if exc.code < HTTP_SERVER_ERROR_FLOOR:
                raise
            last_error = exc
        except OSError as exc:
            last_error = exc
        if attempt < attempts:
            time.sleep(backoff * attempt)
    message = f"{url} unreachable after {attempts} attempts: {last_error}"
    raise RuntimeError(message)


def atomic_write(path: Path, data: bytes) -> None:
    """Write `data` to `path` so a concurrent reader never sees a partial file."""
    staging = path.parent / f"{path.name}.{uuid.uuid4().hex}.tmp"
    staging.write_bytes(data)
    staging.replace(path)


def mirror_external(
    name: str,
    versions: set[str],
    lock_hash: str,
    mirror: Path,
    overlay: Path,
    *,
    no_verify: bool,
    index_base: str = CRATES_IO_INDEX,
    dl_base: str = CRATES_IO_DL,
    timeout: float = FETCH_TIMEOUT_SECONDS,
    attempts: int = FETCH_ATTEMPTS,
    backoff: float = FETCH_BACKOFF_SECONDS,
) -> str:
    """Mirror one external crate's index entry, plus its `.crate` when verified.

    Index responses
    are cached under `mirror` keyed by the lockfile hash, so an unchanged lock
    re-fetches nothing; the cache write is atomic, so two runs sharing a
    cache never serve each other half a response. Fetches carry an explicit
    timeout and bounded retries with backoff, and a failure names the crate,
    the URL, and the attempts spent.

    Returns:
        An error message, or the empty string on success.

    In the `--no-verify` form only index metadata is mirrored: cargo resolves
    a no-verify run from the index alone (an index-only loopback serves a
    `--no-verify` round with no `/dl` request, while the verified form dies on
    the missing download), so the run touches the network only for the
    metadata resolution needs.

    """
    cache = mirror / lock_hash
    raw_path = cache / "index" / f"{name}.lines"
    if not raw_path.is_file():
        raw_path.parent.mkdir(parents=True, exist_ok=True)
        url = f"{index_base}/{index_rel(name)}"
        try:
            raw = fetch_bytes(url, timeout=timeout, attempts=attempts, backoff=backoff)
        except (RuntimeError, urllib.error.HTTPError) as exc:
            return f"crates.io index fetch failed for {name} ({url}): {exc}"
        atomic_write(raw_path, raw)
    wanted = [line for line in raw_path.read_text(encoding="utf-8").splitlines() if line]
    matched = [line for line in wanted if json.loads(line)["vers"] in versions]
    missing = versions - {json.loads(line)["vers"] for line in matched}
    if missing:
        return (
            f"crates.io holds none of {', '.join(sorted(missing))} "
            f"for {name} -- the lockfile pins an unresolvable dependency"
        )
    dest = overlay / "index" / index_rel(name)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("".join(f"{line}\n" for line in matched), encoding="utf-8")
    if no_verify:
        return ""
    for version in versions:
        crate_file = None
        for candidate in sorted(
            (Path.home() / ".cargo" / "registry" / "cache").glob(f"*/{name}-{version}.crate")
        ):
            crate_file = candidate
            break
        if crate_file is None:
            crate_file = cache / "dl" / f"{name}-{version}.crate"
            if not crate_file.is_file():
                crate_file.parent.mkdir(parents=True, exist_ok=True)
                url = f"{dl_base}/{name}/{version}/download"
                try:
                    atomic_write(
                        crate_file,
                        fetch_bytes(url, timeout=timeout, attempts=attempts, backoff=backoff),
                    )
                except (RuntimeError, urllib.error.HTTPError) as exc:
                    crate_file.unlink(missing_ok=True)
                    return f"crates.io download failed for {name}-{version} ({url}): {exc}"
        link = overlay / "dl" / name / version / "download"
        link.parent.mkdir(parents=True, exist_ok=True)
        link.unlink(missing_ok=True)
        link.symlink_to(crate_file)
    return ""


def publish_entry(meta: Json, cksum: str) -> Json:
    """Map one Publish API payload onto its sparse-index entry, mechanically.

    The registry server does not understand the payload; it relocates it into
    the index spelling cargo itself reads back. The mapping is the documented
    Publish API-to-index correspondence: `version_req` becomes `req`, a
    dependency renamed through `package = ...` keeps Cargo's rename convention
    (the alias -- cargo's `explicit_name_in_toml` -- in the entry dependency's
    `name`, the real package name in `package`), features whose definitions
    use v2 syntax (`dep:` or a weak `?/` reference) split into `features2`
    behind the `v: 2` marker, and the checksum is the sha256 of the uploaded
    `.crate` -- the exact bytes a real upload would carry.

    Returns:
        The index entry for the uploaded crate.

    """
    deps: list[Json] = []
    for dep in meta.get("deps", []):
        alias = dep.get("explicit_name_in_toml")
        entry_dep: Json = {
            "name": alias or dep["name"],
            "req": dep.get("version_req", dep.get("req", "")),
            "features": dep.get("features") or [],
            "optional": bool(dep.get("optional")),
            "default_features": bool(dep.get("default_features", True)),
            "target": dep.get("target"),
            "kind": dep.get("kind") or "normal",
        }
        if alias:
            entry_dep["package"] = dep["name"]
        deps.append(entry_dep)
    features = {key: list(values) for key, values in (meta.get("features") or {}).items()}
    features2 = {
        key: values
        for key, values in features.items()
        if any("dep:" in value or "?/" in value for value in values)
    }
    entry: Json = {
        "name": meta["name"],
        "vers": meta["vers"],
        "deps": deps,
        "cksum": cksum,
        "features": {key: values for key, values in features.items() if key not in features2},
        "yanked": False,
    }
    if features2:
        entry["features2"] = features2
        entry["v"] = 2
    # Optional Publish payload fields the index spelling carries under the
    # same names: the MSRV cargo read from the packaged manifest, and the
    # native-library `links` key. Both are carried only when the payload has
    # them, exactly as cargo sent them.
    if meta.get("rust_version"):
        entry["rust_version"] = meta["rust_version"]
    if meta.get("links"):
        entry["links"] = meta["links"]
    return entry


def _store_upload(overlay: Path, body: bytes, port: int, auth: str) -> Json:
    """Parse, store, and index one Publish API upload; return its receipt.

    The upload payload is the framed Publish API shape cargo sends; the
    receipt is one line of `uploads.jsonl`, recording the loopback endpoint
    and the token the upload carried.

    Returns:
        The upload receipt: name, version, file count, checksum, the loopback
        endpoint, and the auth the upload carried.

    Raises:
        ValueError: The frame is malformed or the artifact collides with
            different bytes; the caller answers 500 with the detail.

    """
    (json_len,) = struct.unpack("<I", body[:4])
    meta: Json = json.loads(body[4 : 4 + json_len])
    (tar_len,) = struct.unpack("<I", body[4 + json_len : 8 + json_len])
    tarball = body[8 + json_len : 8 + json_len + tar_len]
    name, version = meta["name"], meta["vers"]
    cksum = hashlib.sha256(tarball).hexdigest()
    artifact = overlay / "dl" / name / version / "download"
    artifact.parent.mkdir(parents=True, exist_ok=True)
    previous = artifact.read_bytes() if artifact.is_file() else None
    if previous is not None and previous != tarball:
        collision = f"{name}-{version} already exists with other bytes"
        raise ValueError(collision)
    artifact.write_bytes(tarball)
    with tarfile.open(fileobj=io.BytesIO(tarball)) as archive:
        files = sum(1 for _ in archive)
    if previous is None:
        entry_path = overlay / "index" / index_rel(name)
        entry_path.parent.mkdir(parents=True, exist_ok=True)
        with entry_path.open("a", encoding="utf-8") as index_file:
            index_file.write(json.dumps(publish_entry(meta, cksum)) + "\n")
    receipt = {
        "name": name,
        "vers": version,
        "files": files,
        "cksum": cksum,
        "endpoint": f"http://127.0.0.1:{port}{PUBLISH_API_PATH}",
        "auth": auth,
    }
    with (overlay / "uploads.jsonl").open("a", encoding="utf-8") as receipt_file:
        receipt_file.write(json.dumps(receipt) + "\n")
    return receipt


def _registry_handler(overlay: Path, token: str) -> type:
    """Build the loopback registry's request handler.

    Three protocol surfaces, all backed by the run's own directory: the sparse
    index under `index/` (entries are cargo's own upload metadata, mapped by
    `publish_entry`, plus the verbatim crates.io mirror), the `.crate` tree
    under `dl/` (uploaded artifacts and mirrored downloads), and the Publish
    API upload endpoint. Uploads require the run's dummy token and append one
    receipt line per upload to `uploads.jsonl` -- the durable proof that every
    upload hit this loopback endpoint under the dummy auth and nothing else.

    Returns:
        The handler class for `ThreadingHTTPServer`.

    """

    class Handler(BaseHTTPRequestHandler):
        def __init__(self, *args: Any, **kwargs: Any) -> None:
            super().__init__(*args, **kwargs)

        # The stdlib protocol names the parameter `format`; the name stays so
        # the override remains call-compatible (a renamed parameter is an
        # invalid override), and the shadowing is the seam's, not ours.
        def log_message(self, format: str, *args: object) -> None:  # ruff: ignore[builtin-argument-shadowing]
            pass

        def _send_body(self, status: int, body: bytes, content_type: str) -> None:
            self.send_response(status)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def _send_json(self, status: int, payload: Json) -> None:
            self._send_body(status, json.dumps(payload).encode("utf-8"), "application/json")

        def _serve_file(self, relative: Path) -> None:
            # Never answer a conditional request with 304: the index is
            # populated mid-run, and python's mtime comparison has second
            # granularity, so a same-second population would otherwise let
            # cargo keep resolving against the empty bytes it cached for this
            # URL.
            del self.headers["If-Modified-Since"]
            del self.headers["If-None-Match"]
            # Traversal fails closed: a `..` component (raw or
            # percent-encoded -- do_GET decodes before this point) or an
            # absolute path would read files outside the run's own overlay,
            # so it is refused before any existence check.
            parts = relative.parts
            if not parts or parts[0] == os.sep or ".." in parts:
                self.send_error(403)
                return
            target = overlay / relative
            if not target.is_file():
                self.send_error(404)
                return
            content_type = (
                "application/octet-stream"
                if target.suffix == ".crate" or target.name == "download"
                else "text/plain"
            )
            self._send_body(200, target.read_bytes(), content_type)

        def do_GET(self) -> None:
            # Percent-encoded segments are decoded before the prefix checks
            # and `_serve_file`'s traversal guard, so an encoded `..` cannot
            # slip through as a literal-looking name.
            path = urllib.parse.unquote(self.path).lstrip("/")
            if path == "index/config.json":
                # `api` is the bare origin: cargo joins its upload path onto
                # it, and `dl` is the `.crate` tree cargo downloads from.
                # http.server sets `server_port` on the bound server outside
                # any type stub, so the attribute read needs the suppression.
                origin = f"http://127.0.0.1:{self.server.server_port}"  # ty: ignore[unresolved-attribute]
                self._send_json(200, {"dl": f"{origin}/dl", "api": origin})
                return
            if path.startswith("index/"):
                self._serve_file(Path("index") / path[len("index/") :])
                return
            if path.startswith("dl/"):
                self._serve_file(Path("dl") / path[len("dl/") :])
                return
            self.send_error(404)

        def do_PUT(self) -> None:
            if self.path != PUBLISH_API_PATH:
                self.send_error(404)
                return
            if self.headers.get("Authorization") != token:
                self._send_json(401, {"errors": [{"detail": "upload denied: wrong token"}]})
                return
            # One bounded step per upload: the payload is parsed, stored,
            # indexed, and receipted inside `_store_upload`, and any defect in
            # what cargo sent is answered, never swallowed.
            try:
                length = int(self.headers["Content-Length"])
                body = self.rfile.read(length)
                _store_upload(
                    overlay,
                    body,
                    self.server.server_port,  # ty: ignore[unresolved-attribute]
                    self.headers.get("Authorization") or "",
                )
            except Exception as exc:  # ruff: ignore[blind-except] -- the client must see the failure
                self._send_json(500, {"errors": [{"detail": str(exc)}]})
                return
            self._send_json(
                200,
                {"warnings": {"invalid_categories": [], "invalid_badges": [], "other": []}},
            )

    return Handler


def serve_registry(overlay: Path, token: str) -> tuple[ThreadingHTTPServer, int]:
    """Serve the loopback registry over loopback on an ephemeral port.

    Binding port 0 lets the OS pick an unbound port at bind time, so no fixed
    port can be pre-bound by something else ahead of the run and no two
    concurrent runs can collide; the returned port is the one actually bound,
    read back after bind. The server runs on a daemon thread: it exists only
    for the run's own cargo invocations and dies with the process.

    Returns:
        The bound server and the port it actually bound.

    """
    server = ThreadingHTTPServer(("127.0.0.1", 0), _registry_handler(overlay, token))
    server.daemon_threads = True
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server, server.server_address[1]


def overlay_run_dir(root: Path) -> Path:
    """Create a fresh overlay directory for one run, under the ignored target tree.

    Two runs never share one: a shared directory forces whoever starts second
    to delete the files the first is serving mid-run. Each run removes only
    its own directory when it finishes.

    Returns:
        The run's own directory path.

    """
    return root / OVERLAY_REL / f"run-{uuid.uuid4().hex}"


def _covered_line(name: str, version: str, files: int) -> str:
    return f"publish-verify covered {name} v{version}: {files} files packaged"


def main(argv: list[str]) -> int:
    """Parse arguments, gate on the census, and run the verification.

    Returns:
        The process exit code: 0 on success, otherwise the first failing
        phase's code.

    """
    parser = argparse.ArgumentParser(description="The publish-verify loopback-registry oracle.")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="tree root")
    parser.add_argument(
        "--keep-overlay",
        action="store_true",
        help="keep the per-run overlay directory after the run (for inspection)",
    )
    args, extra = parser.parse_known_args(argv)
    reject_retargeting(extra)
    exclusions, extra = split_exclusions(extra)
    root = args.root.resolve()
    rust = root / "rust"

    checked = census(root, "--check")
    sys.stdout.write(checked.stdout)
    sys.stderr.write(checked.stderr)
    if checked.returncode != 0:
        return checked.returncode
    blocked = census(root, "--blocked")
    if blocked.returncode != 0:
        sys.stderr.write(blocked.stderr)
        return blocked.returncode
    withheld = sorted(blocked.stdout.split())

    overlay = overlay_run_dir(root)
    mirror = root / MIRROR_REL
    try:
        with run_lock(root, lock_wait_seconds()):
            cargo_home = overlay / "cargo-home"
            cargo_env = cargo_environment(cargo_home)
            (overlay / "index").mkdir(parents=True, exist_ok=True)
            (overlay / "dl").mkdir(parents=True, exist_ok=True)
            cargo_home.mkdir(parents=True, exist_ok=True)
            # The workspace metadata is the first cargo resolution of the run,
            # already under the same-workspace lock.
            meta = run(
                [
                    "cargo",
                    "metadata",
                    "--no-deps",
                    "--format-version",
                    "1",
                    "--manifest-path",
                    str(rust / "Cargo.toml"),
                ],
                cwd=rust,
                capture=True,
                env=cargo_env,
            )
            if meta.returncode != 0:
                sys.stderr.write(meta.stderr)
                return meta.returncode
            packages: dict[str, Json] = {p["name"]: p for p in json.loads(meta.stdout)["packages"]}
            # Validate the exclusions before any cargo work: an unknown name
            # must fail loud, not surface as cargo's own selection error after
            # a partial run.
            unknown = sorted(set(exclusions) - set(packages))
            if unknown:
                fail("--exclude names no workspace member: " + ", ".join(unknown))
            return _verify(
                root,
                rust,
                overlay,
                mirror,
                packages,
                withheld,
                extra,
                cargo_home,
                cargo_env,
                exclusions=set(exclusions),
            )
    finally:
        if not args.keep_overlay:
            shutil.rmtree(overlay, ignore_errors=True)


def _verify(
    root: Path,
    rust: Path,
    overlay: Path,
    mirror: Path,
    packages: dict[str, Json],
    withheld: list[str],
    extra: list[str],
    cargo_home: Path,
    cargo_env: dict[str, str],
    *,
    exclusions: set[str],
) -> int:
    """Populate the loopback registry, then verify the pending members.

    Runs under the same-workspace lock (`main` holds it across the metadata,
    upload, and verify phases), and every cargo invocation carries the run's
    own CARGO_HOME. `exclusions` are members the caller removed from the
    verification set: still uploaded to the loopback (resolution set), never
    given a verify build of their own.

    Returns:
        The process exit code: 0 when every verification round passed,
        otherwise the failing round's code.

    """
    no_verify = "--no-verify" in extra
    forwarded = [flag for flag in extra if flag != "--no-verify"]

    # The registry is up before the config is written (the config names its
    # port), and the config is written after the lockfile is settled: a tree
    # without one gets it generated here against the default sources, under
    # the same-workspace lock so two runs cannot race the shared lockfile.
    server, port = serve_registry(overlay, DUMMY_TOKEN)
    try:
        if not (root / LOCK_REL).is_file():
            lockfile = run(
                ["cargo", "metadata", "--format-version", "1"],
                cwd=rust,
                capture=True,
                env=cargo_env,
            )
            if lockfile.returncode != 0:
                sys.stderr.write(lockfile.stderr)
                return lockfile.returncode
        write_cargo_home_config(cargo_home, port)

        lock_hash = hashlib.sha256((root / LOCK_REL).read_bytes()).hexdigest()
        externals, source_problems = lock_externals(root / LOCK_REL, set(packages))
        for problem in source_problems:
            fail(problem)
        if externals:
            errors: list[str] = []
            with ThreadPoolExecutor(max_workers=16) as pool:
                errors.extend(
                    message
                    for message in pool.map(
                        lambda item: mirror_external(
                            item[0], item[1], lock_hash, mirror, overlay, no_verify=no_verify
                        ),
                        sorted(externals.items()),
                    )
                    if message
                )
            if errors:
                for message in errors:
                    fail(message)

        for name in withheld:
            listing = run(
                ["cargo", "package", "--list", "--allow-dirty", "-p", name],
                cwd=rust,
                capture=True,
                env=cargo_env,
            )
            files = len(listing.stdout.splitlines()) if listing.returncode == 0 else 0
            print(f"publish-blocked {name}: {files} files would package")

        # `publish = false` members are out of the census's scope and cargo
        # skips them; they are not eligible for the covered set -- the set
        # the run certifies is exactly what cargo will upload, so a skipped
        # member must never carry a covered line or a receipt expectation. A
        # member whose publish allowlist NAMES registries fails loud: cargo
        # refuses to carry such a member to any other registry name (and the
        # one registry this run drives is the loopback), so a real upload
        # round could never run beside it anyway.
        covered = []
        for name in sorted(packages):
            if name in withheld:
                continue
            allowlist = packages[name].get("publish")
            if allowlist is None or allowlist is True:
                covered.append(name)
            elif allowlist:
                fail(
                    f"{name} publishes only to {', '.join(allowlist)} -- cargo refuses to "
                    "carry it to the loopback registry, so the run cannot certify it"
                )

        def excludes_for(names: list[str]) -> list[str]:
            return [flag for name in names for flag in ("--exclude", name)]

        if covered:
            # The population round: cargo packages and uploads every covered
            # member in its own dependency order, generating each index entry
            # from the packaged form and polling the loopback index until the
            # entry is visible before its dependents are packaged. No member
            # is built (`--no-verify`): building is the verification round's
            # job, for the members the caller has not excluded.
            clear_cargo_staging(rust)
            population = run(
                [
                    "cargo",
                    "publish",
                    "--registry",
                    UPLOAD_REGISTRY,
                    "--workspace",
                    "--locked",
                    "--allow-dirty",
                    "--no-verify",
                    *excludes_for(withheld),
                    *forwarded,
                ],
                cwd=rust,
                capture=True,
                env=cargo_env,
            )
            if population.returncode != 0:
                sys.stdout.write(population.stdout)
                sys.stderr.write(population.stderr)
                fail(
                    "the loopback population round failed -- the published forms do not "
                    "resolve or upload against the loopback registry"
                )
            receipts: dict[str, Json] = {}
            uploads = overlay / "uploads.jsonl"
            if uploads.is_file():
                for line in uploads.read_text(encoding="utf-8").splitlines():
                    if line.strip():
                        receipt = json.loads(line)
                        receipts[receipt["name"]] = receipt
            # The round succeeded; what it uploaded must be exactly the
            # eligible covered set -- a missing receipt would certify a
            # member the registry never accepted, an unexpected one an
            # upload the run never accounted for.
            problem = receipt_problems(set(covered), set(receipts))
            if problem:
                fail(f"the loopback upload receipts do not match the covered set: {problem}")
            for name in sorted(receipts):
                receipt = receipts[name]
                print(_covered_line(name, receipt["vers"], receipt["files"]))
            for name in covered:
                if name in exclusions:
                    print(
                        f"publish-verify resolution-only {name} v{packages[name]['version']}: "
                        "--exclude keeps it on the loopback index, no verify build"
                    )

        if no_verify or not covered:
            return 0

        # The verification round: cargo verify-builds each still-pending
        # member against the populated registry (its dependents unpack the
        # siblings' uploaded artifacts and compile under the aliases the
        # index entries carry), then aborts each upload -- the run exists to
        # certify, never to publish. Excluded members are cargo's own
        # `--exclude`s here: they were uploaded in the population round and
        # resolve like live crates, but an already-live member cannot be
        # re-uploaded, and re-verifying it is what makes a resumed re-run
        # expensive.
        pending = sorted(set(covered) - exclusions)
        if pending:
            clear_cargo_staging(rust)
            verification = run(
                [
                    "cargo",
                    "publish",
                    "--registry",
                    UPLOAD_REGISTRY,
                    "--workspace",
                    "--locked",
                    "--allow-dirty",
                    "--dry-run",
                    *excludes_for(sorted(set(covered) - set(pending))),
                    *excludes_for(withheld),
                    *forwarded,
                ],
                cwd=rust,
                capture=True,
                env=cargo_env,
            )
            sys.stdout.write(verification.stdout)
            sys.stderr.write(verification.stderr)
            if verification.returncode != 0:
                return verification.returncode
        return 0
    finally:
        server.shutdown()
        server.server_close()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
