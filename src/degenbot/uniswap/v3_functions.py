"""Uniswap V3 swap and burn amount calculations."""

from __future__ import annotations

from fractions import Fraction
from typing import TYPE_CHECKING

from degenbot._ffi import generate_v3_pool_address as _rs_generate_v3_pool_address
from degenbot.utils.bytes import to_0x_hex

if TYPE_CHECKING:
    from collections.abc import Iterable

    from degenbot.types.chain import ChecksummedAddress
    from degenbot.uniswap.v3_types import Pip


def exchange_rate_from_sqrt_price_x96(sqrt_price_x96: int) -> Fraction:
    """Exchange rate from sqrt price x96.

    Returns:
        The exchange rate as a Fraction.

    """
    # ref: https://blog.uniswap.org/uniswap-v3-math-primer

    # equivalent to Fraction(sqrt_price_x96, 2**96)**2
    return Fraction(
        sqrt_price_x96 * sqrt_price_x96,
        6277101735386680763835789423207666416102355444464034512896,  # 2**192
    )


def generate_v3_pool_address(
    deployer_address: str | bytes,
    token_addresses: Iterable[str | bytes],
    fee: Pip,
    init_hash: str | bytes,
) -> ChecksummedAddress:
    """Get the deterministic V3 pool address generated by CREATE2.

    Uses the token address and fee to generate the salt.
    The token addresses can be passed in any order.

    Returns:
        The checksummed pool address.

    Adapted from https://github.com/Uniswap/v3-periphery/blob/0682387198a24c7cd63566a2c58398533860a5d1/contracts/libraries/PoolAddress.sol#L33

    """
    t0, t1 = (to_0x_hex(a) for a in token_addresses)
    return _rs_generate_v3_pool_address(
        to_0x_hex(deployer_address),
        t0,
        t1,
        int(fee),
        to_0x_hex(init_hash),
    )
