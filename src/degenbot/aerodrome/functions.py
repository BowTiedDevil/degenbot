"""Aerodrome deterministic CREATE2 pool-address derivation (EIP-1167 clones).

Delegating shells over the Rust ``compute_aerodrome_v2_pool_address`` /
``compute_aerodrome_v3_pool_address`` pyfunctions (the pure-Rust
``degenbot_uniswap::create2::compute_aerodrome_v2_address`` /
``compute_aerodrome_v3_address`` leaves, re-exported through the
``degenbot.aerodrome.address`` barrier per ADR-013). The Solidly-stable swap
calc is now invoked in-line at its sole call site
(``aerodrome/pools.py::to_hop_state``) via the Rust leaf re-exported by
``degenbot.aerodrome.math``; the redundant Fraction-splitting wrapper that
lived here was deleted (ergo S5SJXF / NFYOWI). These address helpers were
routed through the Rust seam and their pure-Python ``eip_1167_clone_address``
/ ``keccak256`` / ``encode_packed`` / ``abi_encode`` bodies deleted (ergo
S5SJXF / WLJD2Y — the Python functions are now thin pass-throughs; the Rust
``#[cfg(test)]`` corpus is the §4.2 regression set).
"""

from collections.abc import Sequence

from eth_typing import ChecksumAddress

from degenbot.aerodrome.address import (
    compute_aerodrome_v2_pool_address as _rs_compute_aerodrome_v2_pool_address,
)
from degenbot.aerodrome.address import (
    compute_aerodrome_v3_pool_address as _rs_compute_aerodrome_v3_pool_address,
)
from degenbot.checksum_cache import get_checksum_address


def generate_aerodrome_v2_pool_address(
    *,
    deployer_address: str | bytes,
    token_addresses: Sequence[str | bytes],
    implementation_address: str | bytes,
    stable: bool,
) -> ChecksumAddress:
    """Get the deterministic V2 pool address generated by CREATE2.

    Uses the token addresses to generate the salt.
    The token addresses can be passed in any order.

    Adapted from https://github.com/aerodrome-finance/contracts/blob/main/contracts/factories/PoolFactory.sol
    and https://github.com/OpenZeppelin/openzeppelin-contracts/blob/master/contracts/proxy/Clones.sol

    Returns:
        The computed value.

    """
    t0, t1 = token_addresses  # type: ignore[misc]
    # Normalize str|bytes inputs to checksummed hex strings — the Rust leaf
    # parses hex, and this preserves the original HexBytes-based contract.
    return get_checksum_address(
        _rs_compute_aerodrome_v2_pool_address(
            get_checksum_address(deployer_address),
            get_checksum_address(t0),
            get_checksum_address(t1),
            stable,
            get_checksum_address(implementation_address),
        )
    )


