"""Aerodrome deterministic CREATE2 pool-address derivation (EIP-1167 clones).

The Solidly-stable swap calc is now invoked in-line at its sole call site
(``aerodrome/pools.py::to_hop_state``) via the Rust leaf re-exported by
``degenbot.aerodrome.math``; the redundant Fraction-splitting wrapper that
lived here was deleted (ergo S5SJXF / NFYOWI).
"""

from collections.abc import Sequence

from eth_typing import ChecksumAddress
from hexbytes import HexBytes

from degenbot.abi import encode as abi_encode
from degenbot.abi import encode_packed
from degenbot.contract.addresses import eip_1167_clone_address
from degenbot.crypto import keccak256


def generate_aerodrome_v2_pool_address(
    *,
    deployer_address: str | bytes,
    token_addresses: Sequence[str | bytes],
    implementation_address: str | bytes,
    stable: bool,
) -> ChecksumAddress:
    """Get the deterministic V2 pool address generated by CREATE2.

    Uses the token address to generate the salt.
    The token addresses can be passed in any order.

    Adapted from https://github.com/aerodrome-finance/contracts/blob/main/contracts/factories/PoolFactory.sol
    and https://github.com/OpenZeppelin/openzeppelin-contracts/blob/master/contracts/proxy/Clones.sol

    Returns:
        The computed value.

    """
    sorted_token_addresses = sorted([HexBytes(address) for address in token_addresses])

    salt = keccak256(
        encode_packed(
            ["address", "address", "bool"],
            [*sorted_token_addresses, stable],
        ),
    )

    return eip_1167_clone_address(
        deployer=deployer_address,
        implementation_contract=implementation_address,
        salt=salt,
    )


def generate_aerodrome_v3_pool_address(
    deployer_address: str | bytes,
    token_addresses: Sequence[str | bytes],
    implementation_address: str | bytes,
    tick_spacing: int,
) -> ChecksumAddress:
    """Get the deterministic V3 pool address generated by CREATE2.

    Uses the token address to generate the salt.
    The token addresses can be passed in any order.

    Adapted from https://github.com/aerodrome-finance/slipstream/blob/main/contracts/core/CLFactory.sol
    and https://github.com/OpenZeppelin/openzeppelin-contracts/blob/master/contracts/proxy/Clones.sol

    Returns:
        The computed value.

    """
    sorted_token_addresses = sorted([HexBytes(address) for address in token_addresses])

    salt = keccak256(
        abi_encode(
            ["address", "address", "int24"],
            [*sorted_token_addresses, tick_spacing],
        ),
    )

    return eip_1167_clone_address(
        deployer=deployer_address,
        implementation_contract=implementation_address,
        salt=salt,
    )
