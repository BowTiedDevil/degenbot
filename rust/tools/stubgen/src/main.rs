// ADR-066 D2: writes the committed `src/degenbot/_ffi/` stub tree from the
// introspection chunks embedded in a cdylib built with the binding layer's
// `experimental-inspect` feature. Chunk parsing is static (object-file
// symbols only), so the cdylib is never loaded or executed here.
use std::path::Path;

